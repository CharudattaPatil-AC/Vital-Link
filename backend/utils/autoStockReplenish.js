const BloodRequest = require('../models/BloodRequest');
const User = require('../models/User');
const {
  COMPATIBILITY_MATRIX,
  getTierForDonor,
  checkDonorEligibility
} = require('./bloodCompatibility');

const LOW_STOCK_THRESHOLDS = {
  'O-': 4,
  'AB-': 4,
  'B-': 4,
  'A-': 4,
  'O+': 5,
  'A+': 5,
  'B+': 5,
  'AB+': 5
};

/**
 * Checks a blood bank's live inventory and automatically raises emergency
 * donor replenishment requests for any blood group below the safety threshold.
 * 
 * @param {Object} bloodBank - Mongoose BloodBank document
 * @param {Object} io - Socket.IO server instance (optional)
 * @returns {Array} List of newly created automated blood requests
 */
async function checkAndTriggerLowStockRequests(bloodBank, io) {
  if (!bloodBank || !bloodBank.inventory || !bloodBank.location) {
    return [];
  }

  const generatedRequests = [];

  for (const item of bloodBank.inventory) {
    const bg = item.bloodGroup;
    const currentUnits = item.unitsAvailable || 0;
    const threshold = LOW_STOCK_THRESHOLDS[bg] || 5;

    // Trigger auto-request only if stock is at or below threshold
    if (currentUnits <= threshold) {
      // Avoid duplicate spam: check if an active auto-request is already pending
      const existingRequest = await BloodRequest.findOne({
        sourceFacility: bloodBank._id,
        bloodGroup: bg,
        status: 'active'
      });

      if (existingRequest) {
        continue;
      }

      // Calculate replenishment target units needed (restores back to a healthy 12 units buffer)
      const targetBuffer = 12;
      const unitsNeeded = Math.max(5, targetBuffer - currentUnits);

      const isRare = ['O-', 'AB-', 'B-', 'A-'].includes(bg);
      const urgency = (isRare || currentUnits <= 1) ? 'critical' : 'urgent';

      const searchRadius = 15000; // 15 km search radius for auto-replenishment
      const compatibleGroups = COMPATIBILITY_MATRIX[bg] || [bg];

      // Create automated blood request
      const autoRequest = new BloodRequest({
        patient: bloodBank.managedBy,
        bloodGroup: bg,
        compatibleGroups,
        unitsNeeded,
        urgency,
        location: {
          type: 'Point',
          coordinates: bloodBank.location.coordinates || [78.9629, 20.5937]
        },
        radius: searchRadius,
        contactPhone: bloodBank.phone || '+91 1800 11 9999',
        hospitalName: `${bloodBank.name} [Automated Low-Stock Trigger]`,
        status: 'active',
        isAutoGenerated: true,
        sourceFacility: bloodBank._id,
        currentStockWhenRaised: currentUnits
      });

      // Find nearby candidate voluntary donors
      try {
        const candidateDonors = await User.find({
          role: 'donor',
          isAvailable: true,
          bloodGroup: { $in: compatibleGroups },
          location: {
            $near: {
              $geometry: {
                type: 'Point',
                coordinates: bloodBank.location.coordinates
              },
              $maxDistance: searchRadius
            }
          }
        }).select('-password');

        const eligibleDonors = [];
        for (const donor of candidateDonors) {
          const eligibility = checkDonorEligibility(donor);
          if (eligibility.eligible) {
            const { tier, label } = getTierForDonor(bg, donor.bloodGroup);
            eligibleDonors.push({ donor, tier, label });
          }
        }

        eligibleDonors.sort((a, b) => a.tier - b.tier);

        autoRequest.matchedDonors = eligibleDonors.map(d => ({
          donor: d.donor._id,
          donorBloodGroup: d.donor.bloodGroup,
          matchTier: d.tier,
          matchLabel: d.label,
          status: 'pending'
        }));
      } catch (geoErr) {
        console.warn('Geospatial donor matching note:', geoErr.message);
      }

      await autoRequest.save();
      generatedRequests.push(autoRequest);

      // Real-time WebSocket broadcasts
      if (io) {
        // Broadcast to matching donors
        io.emit('bloodRequest', {
          requestId: autoRequest._id,
          bloodGroup: bg,
          unitsNeeded,
          hospitalName: autoRequest.hospitalName,
          urgency,
          isAutoGenerated: true,
          location: autoRequest.location
        });

        // Notify blood bank facility room
        io.to(`facility_${bloodBank._id}`).emit('lowStockAutoRequest', {
          bloodGroup: bg,
          currentUnits,
          requestId: autoRequest._id,
          unitsNeeded,
          matchedDonorsCount: autoRequest.matchedDonors.length
        });
      }

      console.log(
        `⚡ [Auto-Replenish] Low stock triggered for ${bloodBank.name}: ${bg} is at ${currentUnits} units. Automated Request #${autoRequest._id.toString().slice(-6)} created.`
      );
    }
  }

  return generatedRequests;
}

module.exports = {
  LOW_STOCK_THRESHOLDS,
  checkAndTriggerLowStockRequests
};
