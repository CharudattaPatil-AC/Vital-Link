// POST /api/bloodbanks - Create blood bank
exports.createBloodBank = async (req, res) => {
  try {
    const { name, email, phone, address, location } = req.body;

    const existing = await BloodBank.findOne({ managedBy: req.user._id });
    if (existing) {
      return res.status(400).json({ message: 'You already manage a blood bank' });
    }

    const defaultInventory = ['A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-'].map(bg => ({
      bloodGroup: bg,
      unitsAvailable: 0
    }));

    const bloodBank = await BloodBank.create({
      name,
      email,
      phone,
      address,
      location: {
        type: 'Point',
        coordinates: location.coordinates
      },
      managedBy: req.user._id,
      inventory: defaultInventory
    });

    res.status(201).json(bloodBank);
  } catch (error) {
    console.error('Create blood bank error:', error);
    res.status(500).json({ message: 'Server error creating blood bank' });
  }
};

// PUT /api/bloodbanks/:id/inventory - Update blood inventory
exports.updateInventory = async (req, res) => {
  try {
    const bloodBank = await BloodBank.findById(req.params.id);
    if (!bloodBank) {
      return res.status(404).json({ message: 'Blood bank not found' });
    }

    if (bloodBank.managedBy.toString() !== req.user._id.toString() && req.user.role !== 'admin') {
      return res.status(403).json({ message: 'Not authorized to update this blood bank' });
    }

    const { inventory } = req.body;
    if (inventory) {
      bloodBank.inventory = inventory;
    }

    await bloodBank.save();

    const io = req.app.get('io');
    if (io) {
      io.emit('inventoryUpdate', {
        type: 'bloodbank',
        facilityId: bloodBank._id,
        inventory: bloodBank.inventory
      });
    }

    // Automatically check for low stock and raise emergency requests
    const autoRaisedRequests = await checkAndTriggerLowStockRequests(bloodBank, io);

    res.json({
      bloodBank,
      autoRaisedCount: autoRaisedRequests.length,
      autoRaisedRequests
    });
  } catch (error) {
    console.error('Update blood bank inventory error:', error);
    res.status(500).json({ message: 'Server error updating inventory' });
  }
};

// GET /api/bloodbanks/:id/auto-requests - Get automated low-stock requests for this blood bank
exports.getFacilityAutoRequests = async (req, res) => {
  try {
    const bloodBank = await BloodBank.findById(req.params.id);
    if (!bloodBank) {
      return res.status(404).json({ message: 'Blood bank not found' });
    }

    const autoRequests = await BloodRequest.find({
      sourceFacility: bloodBank._id,
      isAutoGenerated: true
    }).sort({ createdAt: -1 });

    res.json(autoRequests);
  } catch (error) {
    console.error('Error fetching facility auto requests:', error);
    res.status(500).json({ message: 'Server error retrieving auto requests' });
  }
};

// POST /api/bloodbanks/:id/auto-check - Manually trigger low stock scan & raise requests
