const mongoose = require('mongoose');
const { getISTDate, getISTString } = require('../utils/istTime');

const bloodRequestSchema = new mongoose.Schema({
  patient: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
  bloodGroup: {
    type: String,
    enum: ['A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-'],
    required: true
  },
  compatibleGroups: [{ type: String }],
  unitsNeeded: { type: Number, required: true },
  urgency: {
    type: String,
    enum: ['critical', 'urgent', 'normal'],
    default: 'normal'
  },
  location: {
    type: { type: String, enum: ['Point'], default: 'Point' },
    coordinates: { type: [Number], required: true }
  },
  radius: { type: Number, default: 5000 },
  status: {
    type: String,
    enum: ['active', 'fulfilled', 'cancelled'],
    default: 'active'
  },
  isAutoGenerated: {
    type: Boolean,
    default: false
  },
  sourceFacility: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'BloodBank'
  },
  currentStockWhenRaised: {
    type: Number,
    default: 0
  },
  matchedBloodBanks: [{
    bloodBank: { type: mongoose.Schema.Types.ObjectId, ref: 'BloodBank' },
    name: String,
    address: String,
    phone: String,
    distanceKm: Number,
    unitsAvailable: Number,
    bloodGroup: String,
    matchTier: { type: Number, default: 1 }, // 1: Exact, 2: Compatible
    matchLabel: String,
    availableStock: [{
      bloodGroup: String,
      unitsAvailable: Number
    }]
  }],
  contactPhone: { type: String, required: true },
  hospitalName: String,
  createdAtIST: { type: String, default: getISTString },
  updatedAtIST: { type: String, default: getISTString }
}, {
  timestamps: {
    currentTime: getISTDate
  }
});

bloodRequestSchema.pre('save', function () {
  const istStr = getISTString();
  if (!this.createdAtIST) {
    this.createdAtIST = istStr;
  }
  this.updatedAtIST = istStr;
});

bloodRequestSchema.index({ location: '2dsphere' });
bloodRequestSchema.index({ sourceFacility: 1, bloodGroup: 1, status: 1 });

module.exports = mongoose.model('BloodRequest', bloodRequestSchema);
