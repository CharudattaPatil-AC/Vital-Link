const mongoose = require('mongoose');

const bloodRequestSchema = new mongoose.Schema({
  patient: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
  bloodGroup: {
    type: String,
    enum: ['A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-'],
    required: true
  },
  compatibleGroups: [{ type: String }],
  unitsNeeded: { type: Number, required: true },
  urgency: {
    type: String,
    enum: ['critical', 'urgent', 'normal'],
    default: 'normal'
  },
  location: {
    type: { type: String, enum: ['Point'], default: 'Point' },
    coordinates: { type: [Number], required: true }
  },
  radius: { type: Number, default: 5000 },
  status: {
    type: String,
    enum: ['active', 'fulfilled', 'cancelled'],
    default: 'active'
  },
  isAutoGenerated: {
    type: Boolean,
    default: false
  },
  sourceFacility: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'BloodBank'
  },
  currentStockWhenRaised: {
    type: Number,
    default: 0
  },
  matchedDonors: [{
    donor: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    donorBloodGroup: String,
    matchTier: { type: Number, default: 1 }, // 1: Exact, 2: Compatible Rh-, 3: Universal Rh+, 4: Universal Reserve
    matchLabel: String,
    status: {
      type: String,
      enum: ['pending', 'accepted', 'declined'],
      default: 'pending'
    },
    respondedAt: Date
  }],
  contactPhone: { type: String, required: true },
  hospitalName: String,

  // Autonomous Blood Dispatch & Escalation Agent Fields
  escalationTier: {
    type: Number,
    default: 1 // Tier 1: 5km, Tier 2: 15km, Tier 3: 30km
  },
  lastEscalatedAt: {
    type: Date,
    default: Date.now
  },
  escalationHistory: [{
    tier: Number,
    radius: Number,
    action: String,
    summary: String,
    timestamp: { type: Date, default: Date.now }
  }],
  dispatchedChannels: [{
    channel: {
      type: String,
      enum: ['websocket', 'whatsapp', 'ivr_call']
    },
    recipientPhone: String,
    recipientName: String,
    distanceKm: Number,
    status: {
      type: String,
      default: 'sent' // 'sent', 'ringing', 'delivered', 'accepted', 'failed'
    },
    messageText: String,
    triggeredAt: { type: Date, default: Date.now }
  }],
  autonomousHold: {
    placed: { type: Boolean, default: false },
    bloodBank: { type: mongoose.Schema.Types.ObjectId, ref: 'BloodBank' },
    bloodBankName: String,
    reservationId: { type: mongoose.Schema.Types.ObjectId, ref: 'Reservation' },
    unitsHeld: { type: Number, default: 0 },
    bloodGroup: String,
    pickupAddress: String,
    contactPhone: String,
    distanceKm: Number,
    routingUrl: String,
    placedAt: Date,
    status: {
      type: String,
      enum: ['active', 'claimed', 'released', 'none'],
      default: 'none'
    }
  }
}, { timestamps: true });

bloodRequestSchema.index({ location: '2dsphere' });
bloodRequestSchema.index({ sourceFacility: 1, bloodGroup: 1, status: 1 });

module.exports = mongoose.model('BloodRequest', bloodRequestSchema);
